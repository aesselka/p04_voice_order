LAST_PREFIXES = ("последн", "соңғы", "сонғы")


def ordinal(word: str):
    """-> int | 'last' | None"""
    if word.startswith(LAST_PREFIXES):
        return "last"
    m = _ORD_RU.match(word)
    if m:
        return _ORD_RU_N[m.group(1)]
    m = _ORD_KK.match(word)
    if m:
        return _ORD_KK_N[m.group(1)]
    return None


SIZE_PREFIXES = [
    (("маленьк", "малень", "малую", "малый", "малое", "кішкентай", "кіші", "small"), Size.S),
    (("средн", "стандарт", "орташа", "medium"), Size.M),
    (("больш", "побольш", "крупн", "үлкен", "улкен", "large", "big"), Size.L),
]


def size_of(word: str):
    for prefixes, size in SIZE_PREFIXES:
        if word.startswith(prefixes):
            return size
    return None


